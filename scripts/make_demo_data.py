THEME_WEIGHTS = {"อกหัก": 1.3, "รักหวาน": 1.3, "ลูกทุ่ง": 1.0, "ปาร์ตี้": 1.0, "กำลังใจ": 0.9,
                 "ชีวิตเมือง": 0.9, "สากล": 0.8}
FILLERS = ["โอ้โอ้โอ้", "เย้เย้", "la la la", "ฮู้ว ฮู้ว", "oh oh oh"]
ARTISTS = [f"Demo Artist {i:02d}" for i in range(1, 41)]
VERSIONS = ["", "", "", " (Acoustic)", " (Live)", " (Remix)", " Ver.2"]


def make_song(rng: random.Random) -> dict:
    themes = list(THEMES)
    primary = rng.choices(themes, weights=[THEME_WEIGHTS[t] for t in themes])[0]
    mean, titles, pool = THEMES[primary]
    secondary = rng.choice([t for t in themes if t != primary]) if rng.random() < 0.35 else None

    verse = rng.sample(pool, k=rng.randint(4, 6))
    chorus = rng.sample(pool, k=rng.randint(2, 3))
    extra = rng.sample(THEMES[secondary][2], k=rng.randint(1, 3)) if secondary else []
    lines = verse[:3] + extra + chorus + verse[3:] + chorus
    if rng.random() < 0.4:
        lines.insert(rng.randrange(len(lines)), rng.choice(FILLERS))
    lines += chorus if rng.random() < 0.5 else []

    if secondary:
        mean = 0.8 * mean + 0.2 * THEMES[secondary][0]
    log_views = min(9.2, max(3.6, rng.gauss(mean, 0.5)))

    return {
        "title": rng.choice(titles) + rng.choice(VERSIONS),
        "artist": rng.choice(ARTISTS),
        "lyrics": "\n".join(lines),
        "views": int(10**log_views),
        "url": "",
        "genre": primary,
    }


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    rng = random.Random(SEED)
    songs, seen = [], set()
    while len(songs) < N_SONGS:
        s = make_song(rng)
        key = (s["title"], s["artist"])
        if key in seen:
            continue
        seen.add(key)
        songs.append(s)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=["title", "artist", "lyrics", "views", "url", "genre"])
        writer.writeheader()
        writer.writerows(songs)
    print(f"สร้างข้อมูลจำลอง {len(songs)} เพลง -> {OUT}")


if __name__ == "__main__":
    main()
